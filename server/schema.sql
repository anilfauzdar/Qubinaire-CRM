CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(120) UNIQUE NOT NULL, full_name VARCHAR(200) NOT NULL,
 password_hash TEXT NOT NULL, role VARCHAR(20) NOT NULL CHECK(role IN ('admin','manager','sales')),
 active BOOLEAN NOT NULL DEFAULT TRUE, manager_id BIGINT REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS leads (
 id VARCHAR(100) PRIMARY KEY, lead_type VARCHAR(20) NOT NULL CHECK(lead_type IN ('student','college')),
 name VARCHAR(200) NOT NULL, phone VARCHAR(80), email VARCHAR(200), institution TEXT,
 course_interest TEXT, city VARCHAR(120), district VARCHAR(120), state VARCHAR(120),
 source VARCHAR(120), status VARCHAR(80) NOT NULL DEFAULT 'new', owner_id BIGINT REFERENCES users(id),
 notes TEXT, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, version INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_leads_owner_updated ON leads(owner_id,updated_at DESC);
CREATE TABLE IF NOT EXISTS api_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_api_sessions_expiry ON api_sessions(expires_at);
CREATE TABLE IF NOT EXISTS devices (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 device_name VARCHAR(120) NOT NULL,
 platform VARCHAR(20) NOT NULL CHECK(platform IN ('android','windows','web')),
 token_hash CHAR(64) NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_devices_user_id ON devices(user_id);
CREATE TABLE IF NOT EXISTS sync_changes (
 seq BIGSERIAL UNIQUE, change_id VARCHAR(80) PRIMARY KEY,
 device_id UUID REFERENCES devices(id), entity VARCHAR(30) NOT NULL,
 record_id VARCHAR(100) NOT NULL, operation VARCHAR(12) NOT NULL CHECK(operation IN ('upsert','delete')),
 payload JSONB NOT NULL DEFAULT '{}'::jsonb, client_updated_at TIMESTAMPTZ, received_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sync_changes_received ON sync_changes(received_at);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGSERIAL PRIMARY KEY, actor_id BIGINT REFERENCES users(id), action TEXT NOT NULL,
 entity TEXT, entity_id TEXT, details TEXT, created_at TIMESTAMPTZ NOT NULL
);


CREATE TABLE IF NOT EXISTS activities (
 id VARCHAR(100) PRIMARY KEY, lead_id VARCHAR(100) NOT NULL REFERENCES leads(id),
 employee_id BIGINT NOT NULL REFERENCES users(id), activity_type TEXT NOT NULL,
 notes TEXT, outcome TEXT, occurred_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS followups (
 id VARCHAR(100) PRIMARY KEY, lead_id VARCHAR(100) NOT NULL REFERENCES leads(id),
 employee_id BIGINT NOT NULL REFERENCES users(id), due_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending', notes TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS daily_reports (
 id VARCHAR(100) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 report_date DATE NOT NULL, calls INTEGER DEFAULT 0, connected_calls INTEGER DEFAULT 0,
 whatsapp_followups INTEGER DEFAULT 0, new_leads INTEGER DEFAULT 0, meetings INTEGER DEFAULT 0,
 college_visits INTEGER DEFAULT 0, admissions INTEGER DEFAULT 0, remarks TEXT,
 submitted_at TIMESTAMPTZ NOT NULL, UNIQUE(user_id,report_date)
);
CREATE TABLE IF NOT EXISTS courses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL, fee DOUBLE PRECISION NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS admissions (
 id VARCHAR(100) PRIMARY KEY, lead_id VARCHAR(100) NOT NULL REFERENCES leads(id),
 course_id BIGINT REFERENCES courses(id), admission_no TEXT UNIQUE NOT NULL,
 total_fee DOUBLE PRECISION NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
 admission_date DATE NOT NULL, created_by BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS payments (
 id VARCHAR(100) PRIMARY KEY, admission_id VARCHAR(100) NOT NULL REFERENCES admissions(id),
 amount DOUBLE PRECISION NOT NULL CHECK(amount>0), mode TEXT, reference TEXT,
 status TEXT NOT NULL DEFAULT 'received', payment_date DATE NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS targets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id), period TEXT NOT NULL,
 start_date DATE NOT NULL, end_date DATE NOT NULL, leads_target INTEGER DEFAULT 0,
 admissions_target INTEGER DEFAULT 0, created_by BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS sync_events (
 id BIGSERIAL PRIMARY KEY, device_id TEXT, record_id TEXT, entity TEXT, status TEXT,
 details TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), work_date DATE NOT NULL,
 check_in TIMESTAMPTZ NOT NULL, check_out TIMESTAMPTZ, note TEXT, UNIQUE(user_id,work_date)
);
CREATE TABLE IF NOT EXISTS incentive_settings (
 id INTEGER PRIMARY KEY CHECK(id=1), collection_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
 admission_bonus DOUBLE PRECISION NOT NULL DEFAULT 0, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS leave_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), leave_type TEXT NOT NULL,
 start_date DATE NOT NULL, end_date DATE NOT NULL, reason TEXT, status TEXT NOT NULL DEFAULT 'pending',
 reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMPTZ, review_note TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS refund_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payment_id VARCHAR(100) NOT NULL REFERENCES payments(id),
 requested_amount DOUBLE PRECISION NOT NULL CHECK(requested_amount>0), reason TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending', requested_by BIGINT NOT NULL REFERENCES users(id),
 reviewed_by BIGINT REFERENCES users(id), reviewed_at TIMESTAMPTZ, review_note TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS incentive_payouts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), period_start DATE NOT NULL,
 period_end DATE NOT NULL, estimated_amount DOUBLE PRECISION NOT NULL, approved_amount DOUBLE PRECISION,
 status TEXT NOT NULL DEFAULT 'pending', approved_by BIGINT REFERENCES users(id),
 approved_at TIMESTAMPTZ, note TEXT, created_at TIMESTAMPTZ NOT NULL,
 UNIQUE(user_id,period_start,period_end)
);
CREATE INDEX IF NOT EXISTS idx_activities_lead ON activities(lead_id,occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_followups_due ON followups(employee_id,due_at);
CREATE INDEX IF NOT EXISTS idx_admissions_lead ON admissions(lead_id);
CREATE INDEX IF NOT EXISTS idx_payments_admission ON payments(admission_id);
CREATE INDEX IF NOT EXISTS idx_attendance_date ON attendance(work_date);

CREATE TABLE IF NOT EXISTS lead_hunter_runs (
 id BIGSERIAL PRIMARY KEY, requested_by BIGINT NOT NULL REFERENCES users(id),
 query TEXT NOT NULL, provider TEXT NOT NULL, results_count INTEGER NOT NULL DEFAULT 0,
 imported_count INTEGER NOT NULL DEFAULT 0, status TEXT NOT NULL, details JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS lead_hunter_candidates (
 id BIGSERIAL PRIMARY KEY, run_id BIGINT REFERENCES lead_hunter_runs(id),
 source_url TEXT NOT NULL UNIQUE, title TEXT NOT NULL, description TEXT,
 status TEXT NOT NULL DEFAULT 'new', lead_id VARCHAR(100) REFERENCES leads(id),
 created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_lead_hunter_candidates_status ON lead_hunter_candidates(status,created_at DESC);
